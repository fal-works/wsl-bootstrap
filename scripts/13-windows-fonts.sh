#!/bin/bash

# Exit on errors, unset variables, and pipeline failures
set -euo pipefail

# Load logger functions: log(), error()
source "$(dirname "${BASH_SOURCE[0]}")/../lib/logger.sh"

# Load environment variables from .env file
source "$(dirname "${BASH_SOURCE[0]}")/../lib/load-env.sh" && load_env || exit 1

# Set defaults if not configured
WINDOWS_USER="${WINDOWS_USER:-}"
WINDOWS_UI_FONT="${WINDOWS_UI_FONT:-}"

WINDOWS_FONTS_DIR="/mnt/c/Windows/Fonts"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/fontconfig/conf.d"
CONFIG_FILE="${CONFIG_DIR}/50-wsl-bootstrap-windows-fonts.conf"
CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/fontconfig"

log "=== Windows Fonts Configuration ==="

# BLOCK: Check prerequisites
# PURPOSE: Fail early if fontconfig, the Windows font folder, or the folder of WINDOWS_USER (if set) is unavailable
# DETAILS: fontconfig is preinstalled on Ubuntu 24.04.
#          WINDOWS_USER is checked against the user's folder rather than the user's font folder,
#          because that folder does not exist until a font is installed for the user.
if ! command -v fc-cache >/dev/null 2>&1; then
    error "fc-cache not found (install the fontconfig package)"
    exit 1
fi
if [ ! -d "${WINDOWS_FONTS_DIR}" ]; then
    error "${WINDOWS_FONTS_DIR} not found"
    exit 1
fi
if [ -n "${WINDOWS_USER}" ] && [ ! -d "/mnt/c/Users/${WINDOWS_USER}" ]; then
    error "Windows user folder not found: /mnt/c/Users/${WINDOWS_USER} (check WINDOWS_USER in .env)"
    exit 1
fi

# BLOCK: Generate the fontconfig configuration
# PURPOSE: Let Linux applications use the fonts installed on Windows under the same names,
#          and optionally use the Windows system UI font as the default sans-serif
# DETAILS: Writes one file to the user's fontconfig conf.d, which fontconfig loads by default.
#          Browsers' own font settings, such as the fonts for serif and monospace, still apply.
# IMPORTANCE: OPTIONAL - Useful for checking from WSL how documents render on Windows.
log "Generating ${CONFIG_FILE}..."
mkdir -p "${CONFIG_DIR}"
{
    cat <<EOF
<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by wsl-bootstrap scripts/13-windows-fonts.sh. Do not edit; change .env and rerun the script. -->
<fontconfig>
  <dir>${WINDOWS_FONTS_DIR}</dir>
EOF
    if [ -n "${WINDOWS_USER}" ]; then
        user_fonts_dir="/mnt/c/Users/${WINDOWS_USER}/AppData/Local/Microsoft/Windows/Fonts"
        # Exclude the Deleted subfolder, where Windows can leave uninstalled fonts.
        # A glob with a leading wildcard did not match in testing, so the full path is used.
        cat <<EOF
  <dir>${user_fonts_dir}</dir>
  <selectfont><rejectfont><glob>${user_fonts_dir}/Deleted/*</glob></rejectfont></selectfont>
EOF
    fi
    # fontconfig names Segoe UI Variable only "Segoe UI Variable", so add the family names under which Windows exposes its instances.
    # They are added at scan time because Chromium ignored a name substituted at match time.
    # The default Text instance has the style "Regular", which the loop does not match, so it has its own rule.
    cat <<'EOF'
  <match target="scan">
    <test name="family"><string>Segoe UI Variable</string></test>
    <test name="style"><string>Regular</string></test>
    <edit name="family" mode="prepend"><string>Segoe UI Variable Text</string></edit>
  </match>
EOF
    for variant in Text Display Small; do
        cat <<EOF
  <match target="scan">
    <test name="family"><string>Segoe UI Variable</string></test>
    <test name="style" compare="contains"><string>${variant}</string></test>
    <edit name="family" mode="prepend"><string>Segoe UI Variable ${variant}</string></edit>
  </match>
EOF
    done
    if [ -n "${WINDOWS_UI_FONT}" ]; then
        cat <<EOF
  <alias>
    <family>sans-serif</family>
    <prefer><family>${WINDOWS_UI_FONT}</family></prefer>
  </alias>
EOF
    fi
    echo "</fontconfig>"
} > "${CONFIG_FILE}"

# BLOCK: Rebuild the font caches
# PURPOSE: Apply the configuration to all applications that use fontconfig
# DETAILS: Fonts must be rescanned, because the Segoe UI Variable names are applied when fonts are scanned
#          and fontconfig caches do not detect configuration changes.
#          fc-cache -f rescans only into caches of its own cache version. Applications that bundle their own
#          fontconfig (e.g. Playwright's Chromium) keep caches of another cache version in the same folder,
#          so all caches are deleted first. Deleted caches are recreated on next use.
log "Rebuilding font caches..."
rm -f "${CACHE_DIR}"/*.cache-*
fc-cache -f

# Verify the configuration was applied
log "Verifying font configuration..."
font_files=$(fc-list : file)
if ! grep -Fq "${WINDOWS_FONTS_DIR}/" <<<"${font_files}"; then
    error "No fonts from ${WINDOWS_FONTS_DIR} are registered"
    exit 1
fi
if [ -n "${WINDOWS_UI_FONT}" ]; then
    sans_serif=$(fc-match -f '%{family}' sans-serif)
    if ! grep -Fq "${WINDOWS_UI_FONT}" <<<"${sans_serif}"; then
        error "sans-serif resolves to '${sans_serif}', not '${WINDOWS_UI_FONT}' (check WINDOWS_UI_FONT in .env)"
        exit 1
    fi
fi

log "✓ Windows fonts configuration complete"
if [ -n "${WINDOWS_UI_FONT}" ]; then
    log "  Default sans-serif: ${WINDOWS_UI_FONT}"
fi
